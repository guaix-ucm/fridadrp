import numpy as np
from pathlib import Path
from rich_argparse import RichHelpFormatter
from scipy.spatial import cKDTree
import teareduce as tea

from numina.tools.initialize_script_with_args import NuminaScriptDefinition

from fridadrp.core import FRIDA_NAXIS1_HAWAII, FRIDA_NAXIS2_HAWAII
from fridadrp.core import FRIDA_NSLICES
from fridadrp.core import FRIDA_NAXIS2_HAWAII_FIRST_USEFUL_PIXEL, FRIDA_NAXIS2_HAWAII_LAST_USEFUL_PIXEL
from fridadrp.core import set_hawaii_border_pixels_to_nan
from fridadrp.core import sliceid_from_sliceindex
from fridadrp.core import slicenum_list_from_slice_lists
from fridadrp.tools.find_arc_lines import retrieve_initial_data
from fridadrp.tools.overplot_slice_boundary_polynomials import plot_fitted_boundary_polynomials


def fill_voronoi_kdtree(array, pixel_scale=(1.0, 1.0), max_distance=np.inf):
    """
    Fill NaN pixels with the value of the nearest valid pixel using a
    k-d tree. Pixels farther than `max_distance` from any valid pixel
    are left as NaN.

    Parameters
    ----------
    array : ndarray, shape (ny, nx)
        2D array with NaN at unknown pixels.
    pixel_scale : tuple of float, optional
        Pixel size along (y, x), used to scale pixel indices to
        physical coordinates.
    max_distance : float, optional
        Maximum distance (in the units of `pixel_scale`) to a valid
        pixel for a NaN pixel to be filled.

    Returns
    -------
    filled : ndarray, shape (ny, nx)
        Copy of `array` with NaN replaced where a valid pixel lies
        within `max_distance`.
    """
    array = np.asarray(array, dtype=float)
    valid = ~np.isnan(array)

    if not valid.any():
        raise ValueError("The array contains no valid (non-NaN) pixels.")

    # Coordinates (in physical units) of all pixels of the grid
    yy, xx = np.indices(array.shape)
    coords = np.column_stack([yy.ravel() * pixel_scale[0], xx.ravel() * pixel_scale[1]])

    # Tree built only on the valid pixels (the Voronoi seeds)
    seeds = coords[valid.ravel()]
    tree = cKDTree(seeds)

    # Nearest seed for every pixel; dist = inf if beyond max_distance
    dist, idx = tree.query(coords, distance_upper_bound=max_distance)

    values = array[valid]  # seed values, same order as seeds
    filled = np.full(array.size, np.nan)
    found = np.isfinite(dist)  # idx == len(seeds) where not found
    filled[found] = values[idx[found]]

    return filled.reshape(array.shape)


def finite_limits(array, method="zscale"):
    """
    Compute display limits using only the finite values of an array.

    Parameters
    ----------
    array : ndarray
        Input array (may contain NaN or inf).
    method : {'zscale', 'minmax'}, optional
        Method used to compute the limits.

    Returns
    -------
    limits : tuple of float or None
        (vmin, vmax), or None if `array` has no finite values.
    """
    values = np.asarray(array)[np.isfinite(array)]
    if values.size == 0:
        return None
    if method == "zscale":
        return ZScaleInterval().get_limits(values)
    elif method == "minmax":
        return MinMaxInterval().get_limits(values)
    else:
        raise ValueError(f"Unknown method: {method}")


def analyze_arc_lines(
    image,
    input_poly,
    voffset=[0.0],
    findarc_file=None,
    xlim=None,
    ylim=None,
    vlim=None,
    slicenum_list=[0],
    sliceid_list=[0],
    show_sliceid=False,
):
    """Analyze arc lines in a FRIDA IFU image.

    Parameters
    ----------
    image : str
        Path to the input FITS image file.
    input_poly : str
        Path to the input FITS file containing the slice boundary polynomials.
    voffset : list of float, optional
        Vertical offsets to apply to the polynomial boundaries (pixels).
        If more than one value is provided, a polynomial of degree len(voffset)-1
        will be fitted to the offsets and applied to the displayed
        slice boundary polynomials. A positive value shifts the
        displayed polynomials upwards (i.e., towards higher array indices
        along NAXIS2).
    findarc_file : str
        Path to the input FITS file containing the detected arc lines.
        This file is generated by the `find_arc_lines` function and contains
        the arc line detections for each slice.
    xlim : list, optional
        The x-axis limits for the plot.
    ylim : list, optional
        The y-axis limits for the plot.
    vlim : list, optional
        The vertical axis limits for the plot.
    slicenum_list : list of int, optional
        List of slice numbers to process (1-based). If [0], all slices
        will be processed. This parameter is mutually exclusive with `sliceid_list`.
    sliceid_list : list of int, optional
        List of slice IDs to process (1-based). If [0], all slices
        will be processed. This parameter is mutually exclusive with `slicenum_list`.
    show_sliceid : bool, optional
        If True, overplot the slice ID at the center of each slice.

    """
    logger = logging.getLogger(__name__)

    # Store the original xlim and ylim values for later use in the plotting
    xlim_plot = xlim
    ylim_plot = ylim

    # Retrieve initial data
    image_data, list_poly_left, list_poly_right, xlim = retrieve_initial_data(image, input_poly, xlim, voffset)
    header = fits.getheader(image)
    fwhm_diffraction = header.get("FWHMDIFF")

    # Define slice numbers to process based on the provided slicenum_list and sliceid_list
    slicenum_to_process = slicenum_list_from_slice_lists(slicenum_list, sliceid_list)
    logger.debug(f"Slices to process: #{slicenum_to_process}")

    # Read the findarc_file to get the detected arc lines for each slice
    with fits.open(findarc_file) as hdul:
        logger.debug(f"Reading arc line detections from {findarc_file}")
        list_arc_line_tables = []
        for islice in range(FRIDA_NSLICES):
            extname = f"SLCNUM{islice + 1:02d}"
            if extname in hdul:
                slice_hdu = hdul[extname]
                arc_line_table = Table(slice_hdu.data)
            else:
                arc_line_table = None
            list_arc_line_tables.append(arc_line_table)

    # Define 2D arrays to store the background-subtracted image, FWHM, skewness,
    # and Strehl ratio for each pixel in the image
    image_fwhm_np = np.full((FRIDA_NAXIS2_HAWAII.value, FRIDA_NAXIS1_HAWAII.value), np.nan, dtype=float)
    image_skewness = np.full((FRIDA_NAXIS2_HAWAII.value, FRIDA_NAXIS1_HAWAII.value), np.nan, dtype=float)
    image_strehl = np.full((FRIDA_NAXIS2_HAWAII.value, FRIDA_NAXIS1_HAWAII.value), np.nan, dtype=float)

    # Main loop over the slices to process the detected arc lines and fill the corresponding values in the 2D arrays
    for islice in range(FRIDA_NSLICES):
        slicenum = islice + 1
        sliceid = sliceid_from_sliceindex(islice)
        if slicenum not in slicenum_to_process:
            logger.debug("Skipping slice #%2d / %2d (Slice ID: %2d)", slicenum, FRIDA_NSLICES, sliceid)
            continue  # Skip this slice if it is not in the list of slices to process

        logger.info("Processing slice #%2d / %2d (Slice ID: %2d)", slicenum, FRIDA_NSLICES, sliceid)

        # Check if the polynomial boundaries for the current slice are valid
        if list_poly_left[islice] is None or list_poly_right[islice] is None:
            logger.warning(
                "Slice #%2d (Slice ID: %2d) has no valid polynomial boundaries. Skipping this slice.",
                slicenum,
                sliceid,
            )
            continue  # Skip this slice if the polynomial boundaries are not valid

        # Create a copy of the image data to work on the current slice
        image_slice = image_data.copy()

        # Set to NaN the pixels outside the useful detector region
        logger.debug("Setting to NaN the pixels outside the useful detector region for slice #%2d", slicenum)
        image_slice = set_hawaii_border_pixels_to_nan(image_slice, inplace=True)

        # Set to NaN the pixels outside the slice boundaries
        logger.debug("Setting to NaN the pixels outside the slice boundaries for slice #%2d", slicenum)
        for j in range(FRIDA_NAXIS1_HAWAII.value):
            yleft = int(list_poly_left[islice](j) + 0.5)
            if yleft >= FRIDA_NAXIS2_HAWAII_FIRST_USEFUL_PIXEL.value - 1:
                image_slice[:yleft, j] = np.nan
            yright = int(list_poly_right[islice](j) + 0.5)
            if yright <= FRIDA_NAXIS2_HAWAII_LAST_USEFUL_PIXEL.value - 1:
                image_slice[yright + 1 :, j] = np.nan

        # automatic limits for the y-axis (NAXIS2) based on the polynomial boundaries of the slices
        xdum = np.arange(FRIDA_NAXIS1_HAWAII.value)
        extra_yroom = 2  # pixels
        ymin = max(-0.5, np.min(list_poly_left[islice](xdum)) - extra_yroom)
        ymax = min(FRIDA_NAXIS2_HAWAII.value - 0.5, np.max(list_poly_right[islice](xdum)) + extra_yroom)
        ylim = [ymin, ymax]
        if ylim[0] < -0.5:
            ylim[0] = -0.5
        if ylim[1] > FRIDA_NAXIS2_HAWAII.value - 0.5:
            ylim[1] = FRIDA_NAXIS2_HAWAII.value - 0.5
        logger.debug("Automatic y-axis limits for slice #%2d: [%.2f, %.2f]", slicenum, ylim[0], ylim[1])

        # Define 2D arrays to store the FWHM, skewness, and Strehl ratio for each pixel in the current slice
        slice_fwhm_np = np.full((FRIDA_NAXIS2_HAWAII.value, FRIDA_NAXIS1_HAWAII.value), np.nan, dtype=float)
        slice_skewness = np.full((FRIDA_NAXIS2_HAWAII.value, FRIDA_NAXIS1_HAWAII.value), np.nan, dtype=float)
        slice_strehl = np.full((FRIDA_NAXIS2_HAWAII.value, FRIDA_NAXIS1_HAWAII.value), np.nan, dtype=float)

        # Loop over the detected arc lines for the current slice and fill the corresponding values in the 2D arrays
        logger.debug("Filling FWHM, skewness, and Strehl ratio for slice #%2d", slicenum)
        arc_line_table = list_arc_line_tables[islice]
        for k in range(len(arc_line_table)):
            ii = int(arc_line_table["x_peak"][k] + 0.5)  # convert to integer index
            # Check if ii is within the valid range of x indices;
            # if not, set it to None to avoid storing values outside the array bounds
            if ii < 0 or ii >= FRIDA_NAXIS1_HAWAII.value:
                ii = None
            if ii is not None:
                j = arc_line_table["row_index"][k]
                fwhm_np = arc_line_table["fwhm_np"][k]
                if fwhm_np is not None and not np.isnan(fwhm_np):
                    slice_fwhm_np[j, ii] = fwhm_np
                skewness = arc_line_table["skewness"][k]
                if skewness is not None and not np.isnan(skewness):
                    slice_skewness[j, ii] = skewness
                strehl = arc_line_table["strehl"][k]
                if strehl is not None and not np.isnan(strehl):
                    slice_strehl[j, ii] = strehl

        # Fill the NaN pixels in the slice arrays using the Voronoi filling function
        logger.debug("Filling NaN pixels in the slice arrays for slice #%2d using Voronoi filling", slicenum)
        mask_slice = np.isfinite(image_slice)  # define a mask for the pixels that are within the slice boundaries
        if np.isfinite(slice_fwhm_np).any():
            filled_slice_fwhm_np = fill_voronoi_kdtree(slice_fwhm_np)
            image_fwhm_np[mask_slice] = filled_slice_fwhm_np[mask_slice]
        else:
            logger.warning("Slice #%2d has no valid FWHM measurements. Skipping FWHM filling.", slicenum)
        if np.isfinite(slice_skewness).any():
            filled_slice_skewness = fill_voronoi_kdtree(slice_skewness)
            image_skewness[mask_slice] = filled_slice_skewness[mask_slice]
        else:
            logger.warning("Slice #%2d has no valid skewness measurements. Skipping skewness filling.", slicenum)
        if np.isfinite(slice_strehl).any():
            filled_slice_strehl = fill_voronoi_kdtree(slice_strehl)
            image_strehl[mask_slice] = filled_slice_strehl[mask_slice]
        else:
            logger.warning("Slice #%2d has no valid Strehl measurements. Skipping Strehl filling.", slicenum)

    # Create a 2x2 grid of subplots to display the summary panels
    fig, axarr = plt.subplots(nrows=2, ncols=2, figsize=(12, 8), sharex=True, sharey=True)
    ax1, ax2, ax3, ax4 = axarr.flatten()

    # Display the four summary panels; a panel without finite values is not displayed
    panels = [
        (ax1, image_data, f"Input image: {Path(image).name} (background-subtracted)", {}),
        (ax2, image_fwhm_np, "FWHM of valid arc lines", {"cmap": "viridis", "cblabel": "FWHM (pixels)"}),
        (ax3, image_skewness, "Skewness of valid arc lines", {"cmap": "viridis", "cblabel": "Skewness"}),
        (
            ax4,
            image_strehl,
            f"Strehl of valid arc lines (assuming FWHM-diffraction = {fwhm_diffraction} pixels)",
            {"cmap": "viridis", "cblabel": "Strehl"},
        ),
    ]
    dict_img = {}  # image returned by tea.imshow for each displayed panel
    for ax, data, title, kwargs in panels:
        if ax == ax1 and vlim is not None:
            limits = vlim
        else:
            limits = finite_limits(data)
        if limits is None:
            logger.warning("No valid values for panel '%s'. Panel not displayed.", title)
            ax.set_title(title)
            ax.text(0.5, 0.5, "No valid measurements", ha="center", va="center", transform=ax.transAxes)
            dict_img[ax] = None
        else:
            vmin, vmax = limits
            dict_img[ax], _, _ = tea.imshow(fig, ax, data, vmin=vmin, vmax=vmax, aspect="auto", title=title, **kwargs)
            if ax == ax1:
                if xlim_plot is not None:
                    ax.set_xlim(xlim_plot)
                if ylim_plot is not None:
                    ax.set_ylim(ylim_plot)
            if show_sliceid:
                for islice in range(FRIDA_NSLICES):
                    slicenum = islice + 1
                    if slicenum not in slicenum_to_process:
                        continue  # Skip this slice if it is not in the list of slices to process
                    plot_fitted_boundary_polynomials(
                        ax,
                        list_poly_left,
                        list_poly_right,
                        show_sliceid=show_sliceid,
                        isliceplot=islice,
                        plot_left_boundary=False,
                        plot_right_boundary=False,
                    )

    for islice in range(FRIDA_NSLICES):
        slicenum = islice + 1
        sliceid = sliceid_from_sliceindex(islice)
        # Check that the detected arc lines for the current slice are available
        arc_line_table = list_arc_line_tables[islice]
        if arc_line_table is None or len(arc_line_table) == 0:
            logger.warning(
                "Slice #%2d (Slice ID: %2d) has no detected arc lines. Skipping this slice.",
                slicenum,
                sliceid,
            )
            continue  # Skip this slice if there are no detected arc lines

        # Count the number of detected arc lines for the current slice
        valid_arc_lines = set(arc_line_table["feature_id"])
        num_valid_arc_lines = len(valid_arc_lines)
        logger.debug("Slice #%2d (Slice ID: %2d) has %d detected arc lines.", slicenum, sliceid, num_valid_arc_lines)
        for k in range(len(arc_line_table)):
            ax1.plot(arc_line_table["x_peak"][k], arc_line_table["row_index"][k], "C1+", markersize=2)

    mouse_info = {"ax": None, "x": None, "y": None}

    def on_mouse_move(event):
        if event.inaxes in [ax1, ax2, ax3, ax4]:
            mouse_info["ax"] = event.inaxes
            mouse_info["x"] = event.xdata
            mouse_info["y"] = event.ydata

    fig.canvas.mpl_connect("motion_notify_event", on_mouse_move)

    def on_key(event):
        ax_mouse = mouse_info["ax"]
        if event.key in [",", "/"]:
            if ax_mouse in [ax1, ax2, ax3, ax4]:
                xmin, xmax = list(ax_mouse.get_xlim())
                ymin, ymax = list(ax_mouse.get_ylim())
                ixmin = int(round(xmin))
                ixmax = int(round(xmax))
                iymin = int(round(ymin))
                iymax = int(round(ymax))
                if ixmin > ixmax:
                    ixmin, ixmax = ixmax, ixmin
                if iymin > iymax:
                    iymin, iymax = iymax, iymin
                if ixmin < 1:
                    ixmin = 1
                if ixmax > FRIDA_NAXIS1_HAWAII.value:
                    ixmax = FRIDA_NAXIS1_HAWAII.value
                if iymin < 1:
                    iymin = 1
                if iymax > FRIDA_NAXIS2_HAWAII.value:
                    iymax = FRIDA_NAXIS2_HAWAII.value
                region2d = tea.SliceRegion2D(f"[{ixmin}:{ixmax},{iymin}:{iymax}]", mode="fits").python
                method = "minmax" if event.key == "," else "zscale"
                for ax, data, _, _ in panels:
                    if ax_mouse == ax and dict_img[ax] is not None:
                        limits = finite_limits(data[region2d], method=method)
                        if limits is not None:  # do nothing if the visible region has no finite values
                            dict_img[ax].set_clim(*limits)
                            ax.figure.canvas.draw_idle()

    fig.canvas.mpl_connect("key_press_event", on_key)

    fig.tight_layout()
    plt.show()


def main(args=None):

    parser = argparse.ArgumentParser(
        description="Analyze arc lines in FRIDA IFU images",
        formatter_class=RichHelpFormatter,
    )
    parser.add_argument("--image", help="Input arc image (mandatory)", type=str, required=True)
    parser.add_argument(
        "--poly", help="Path to the file with the boundary polynomials (mandatory)", type=str, required=True
    )
    parser.add_argument(
        "--voffset",
        help="Vertical offset to apply to the slice boundaries (default: 0.0 pixels; + upward, - downward). "
        "If more than one value is provided, a polynomial of degree len(voffset)-1 will be fitted "
        "to the offsets and applied to the slice boundaries.",
        type=float,
        nargs="+",
        default=[0.0],
    )
    parser.add_argument(
        "--findarc-file",
        help="Path to the file with the arc line detections (mandatory)",
        type=str,
        required=True,
    )
    parser.add_argument(
        "--slicenum-list",
        help=f"Slice number (from 1 to {FRIDA_NSLICES}; 0=ALL, default)",
        type=int,
        nargs="+",
        default=[0],
        choices=list(range(0, FRIDA_NSLICES + 1)),
    )
    parser.add_argument(
        "--sliceid-list",
        help=f"Slice ID (from 1 to {FRIDA_NSLICES}; 0=ALL, default)",
        type=int,
        nargs="+",
        default=[0],
        choices=list(range(0, FRIDA_NSLICES + 1)),
    )
    parser.add_argument("--show-sliceid", help="Overplot slice ID", action="store_true")
    parser.add_argument(
        "--xlim",
        help="X-axis limits for the plot (xmin, xmax); array indices (1-based along NAXIS1 axis)",
        type=float,
        nargs=2,
        default=None,
    )
    parser.add_argument(
        "--ylim",
        help="Y-axis limits for the plot (ymin, ymax); array indices (1-based along NAXIS2 axis)",
        type=float,
        nargs=2,
        default=None,
    )
    parser.add_argument(
        "--vlim",
        help="Background and foreground limits (vmin, vmax)",
        type=float,
        nargs=2,
        default=None,
    )

    # Include default arguments for common actions, and initialize console and logging
    myscript = NuminaScriptDefinition(parser, argv=args)
    args = myscript.args
    logger = myscript.logger

    # Find and characterize arc lines in the image using the provided parameters
    logger.debug("Calling find_arc_lines script function")
    analyze_arc_lines(
        image=args.image,
        input_poly=args.poly,
        voffset=args.voffset,
        findarc_file=args.findarc_file,
        xlim=args.xlim,
        ylim=args.ylim,
        vlim=args.vlim,
        slicenum_list=args.slicenum_list,
        sliceid_list=args.sliceid_list,
        show_sliceid=args.show_sliceid,
    )

    # Display goodbye message and save console if recording is enabled
    myscript.goodbye_message_and_save_console()


if __name__ == "__main__":
    main()
